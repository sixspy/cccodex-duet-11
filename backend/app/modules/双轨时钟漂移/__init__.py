"""双轨时钟漂移：裁窗以事件时为准，处理时只决定旁路或缓冲落处。

基线口径「不裁」保持双轨对齐 happy path 不变；严格/缓冲两形态须显式切换。
- 事件时严格：只看事件时；事件时出窗即进旁路账册，不入对齐差。
- 处理时缓冲：处理时入窗先落缓冲物化包，批末再按事件时重裁。

事件时缺失或非法一律驳回，绝不静默用处理时冒充事件时。
窗口按 UTC 左闭右开 [开始, 结束)。
"""

NAME = "双轨时钟漂移"
已实现 = True

口径_不裁 = "不裁"
口径_严格 = "事件时严格"
口径_缓冲 = "处理时缓冲"
口径集 = (口径_不裁, 口径_严格, 口径_缓冲)

命_不裁 = "不裁-全入"
命_可对齐 = "可对齐"
命_迟到 = "可对齐-迟到"
命_旁路 = "旁路"
命_缓冲 = "缓冲待批末"
命_窗外 = "窗外"
命_驳非法 = "驳回-事件时非法"
命_驳处理时 = "驳回-处理时非法"

落_无 = "无"
落_旁路 = "旁路账册"
落_缓冲 = "缓冲包"

包_待批末 = "待批末"
包_已重裁 = "已重裁"
包_已出账 = "已出账"


def 校验口径(值: str) -> None:
    if 值 not in 口径集:
        raise ValueError(f"未知时钟口径：{值}；可选 {'/'.join(口径集)}")


def 定命(口径值: str, 事件窗内: bool, 处理窗内: bool) -> tuple[str, int, str]:
    """纯判定：返回 (命运, valid, 落处)，不碰库。

    事件时入窗 → 可对齐（处理时也入窗）或迟到可对齐（处理时出窗）。
        迟到仍以事件时为准，故 valid=1；处理时只作标记。
    事件时出窗且处理时入窗 → 严格形态进旁路账册；缓冲形态进缓冲包待批末。
    两时均出窗 → 窗外，不落任何账册。
    """
    if 口径值 == 口径_不裁:
        return 命_不裁, 1, 落_无
    if 事件窗内:
        return (命_可对齐 if 处理窗内 else 命_迟到), 1, 落_无
    if 口径值 == 口径_严格:
        return (命_旁路, 0, 落_旁路) if 处理窗内 else (命_窗外, 0, 落_无)
    if 口径值 == 口径_缓冲:
        return (命_缓冲, 0, 落_缓冲) if 处理窗内 else (命_窗外, 0, 落_无)
    raise ValueError(f"未知时钟口径：{口径值}")


