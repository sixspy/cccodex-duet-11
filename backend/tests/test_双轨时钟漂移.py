    assert 对齐.跑对齐()["键总数"] == 0
    # 把事件时改到窗内，批末重裁应回正
    conn = 连接()
    conn.execute("UPDATE 时钟缓冲包 SET 事件时=? WHERE 事件编号=?", ("2026-11-23T09:00:00Z", "L-b"))
    conn.commit()
    conn.close()
    r = 时钟.批末重裁()
    assert r["入窗回正"] == 1 and r["转旁路"] == 0
    assert 时钟.缓冲待批末计数() == 0
    行 = [x for x in 目录_左() if x["事件编号"] == "L-b"][0]
    assert 行["命运"] == "已入左"
