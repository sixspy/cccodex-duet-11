def test_已出账包在重裁下保持终态():
    """批末已出账是稳定终态：重申同口径不得把它回退成待批末，
    也不得删掉它的旁路行（否则等于悄悄撤销一次批末重裁）。"""
    _设(钟.口径_缓冲)
    _装左("L-settled", "K-settled", 事件时="2026-11-22T10:00:00Z", 处理时="2026-11-23T10:00:00Z")
    时钟.批末重裁()
    assert 时钟.旁路计数() == 1 and 时钟.缓冲待批末计数() == 0
    r = 时钟.重裁存量(钟.口径_缓冲)
    assert r["转缓冲"] == 0 and r["转旁路"] == 0
    assert 时钟.旁路计数() == 1, "已出账的旁路行不得被重裁删掉"
    assert 时钟.缓冲列表()[0]["包状态"] == 钟.包_已出账
    行 = [x["命运"] for x in 目录_左() if x["事件编号"] == "L-settled"]
    assert 行 == ["旁路-时钟出窗"]
    # 反复重裁仍幂等
    assert 时钟.重裁存量(钟.口径_缓冲)["转缓冲"] == 0
    assert 时钟.旁路计数() == 1


