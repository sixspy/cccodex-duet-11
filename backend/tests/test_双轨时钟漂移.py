def test_缓冲先落包批末重裁入窗回正():
    _设(钟.口径_缓冲)
    # 事件时在窗外，但处理时在窗内 → 先入缓冲包
    _装左("L-b", "K-b", 事件时="2026-11-22T22:00:00Z", 处理时="2026-11-23T10:00:00Z")
    assert 时钟.缓冲待批末计数() == 1
