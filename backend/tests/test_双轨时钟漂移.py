# ---------- 并发 ----------

def test_并发批末重裁不双落():
    _设(钟.口径_缓冲)
    for i in range(8):
        _装左(f"L-con-{i}", f"K-con-{i}", 事件时="2026-11-22T22:00:00Z",
              处理时="2026-11-23T10:00:00Z")
    assert 时钟.缓冲待批末计数() == 8
    结果 = []
    错 = []

    def 跑():
        try:
            结果.append(时钟.批末重裁())
        except Exception as e:  # noqa: BLE001
            错.append(e)

    线程 = [threading.Thread(target=跑) for _ in range(4)]
    for t in 线程:
        t.start()
    for t in 线程:
        t.join()
    assert not 错, 错
    assert 时钟.旁路计数() == 8, "并发重裁不得重复落旁路"
    assert 时钟.缓冲待批末计数() == 0
    assert sum(r["转旁路"] for r in 结果) == 8


def test_并发装载不双成功():
    """并发装同一事件编号：唯一键 + IMMEDIATE 下只允许一笔入流。"""
    _设(钟.口径_严格)
    成 = []
    错 = []

    def 跑():
        try:
            成.append(_装左("L-dup", "K-dup")["入流"])
        except Exception as e:  # noqa: BLE001
            错.append(e)

    线程 = [threading.Thread(target=跑) for _ in range(4)]
    for t in 线程:
        t.start()
    for t in 线程:
        t.join()
    conn = 连接()
    n = conn.execute("SELECT COUNT(*) c FROM 左轨流水 WHERE 事件编号='L-dup'").fetchone()["c"]
    conn.close()
    assert n == 1, "并发重复装载不得双落流水"
    assert sum(成) == 1


